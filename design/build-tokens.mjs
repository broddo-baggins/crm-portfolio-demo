// Generates src/styles/tokens.css from design/tokens.json.
// Run: node design/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

// "#C24816" -> "17 79% 42%" (the shadcn convention: hsl(var(--x)))
const hsl = (hex) => {
  const n = hex.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h *= 60;
  }
  return `${h.toFixed(1)} ${(s * 100).toFixed(1)}% ${(l * 100).toFixed(1)}%`;
};

const tok = Object.fromEntries(t.color.tokens.map((x) => [x.name, x]));
const S = t.color.scales;

// shadcn/ui semantic variables, mapped onto the system's tokens.
const semantic = (mode) => {
  const v = (name) => tok[name][mode];
  const dark = mode === "dark";
  return {
    background: v("paper"),
    foreground: v("text"),
    card: v("surface"),
    "card-foreground": v("text"),
    popover: v("surface"),
    "popover-foreground": v("text"),
    primary: v("action"),
    "primary-foreground": dark ? S.ink["950"] : "#FFFFFF",
    secondary: dark ? "#1E252D" : S.ink["100"],
    "secondary-foreground": v("text"),
    muted: v("surface-sunken"),
    "muted-foreground": v("text-muted"),
    accent: dark ? "#1E252D" : S.ink["50"],
    "accent-foreground": v("text"),
    destructive: dark ? S.brick["400"] : S.brick["600"],
    "destructive-foreground": dark ? S.ink["950"] : "#FFFFFF",
    border: v("line"),
    input: v("line-strong"),
    ring: v("focus"),
    sidebar: v("surface"),
    "sidebar-background": v("surface"),
    "sidebar-foreground": v("text-secondary"),
    "sidebar-primary": v("action"),
    "sidebar-primary-foreground": dark ? S.ink["950"] : "#FFFFFF",
    "sidebar-accent": v("action-soft"),
    "sidebar-accent-foreground": dark ? S.ember["300"] : S.ember["700"],
    "sidebar-border": v("line"),
    "sidebar-ring": v("focus"),
    "chart-1": t.color.chart["1"],
    "chart-2": dark ? S.steel["300"] : t.color.chart["2"],
    "chart-3": t.color.chart["3"],
    "chart-4": dark ? S.moss["300"] : t.color.chart["4"],
    "chart-5": t.color.chart["5"],
  };
};

const lines = [];
lines.push("/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit by hand. */");
// `:root:root` outranks daisyUI's own `:root` variables (it defines --border as a width).
lines.push(":root:root {");
for (const [scale, steps] of Object.entries(S)) {
  for (const [k, val] of Object.entries(steps)) if (k !== "usage") lines.push(`  --${scale}-${k}: ${val};`);
}
for (const x of t.color.tokens) lines.push(`  --${x.name}: ${x.light};`);
for (const [k, val] of Object.entries(t.color.heat)) if (k !== "usage") lines.push(`  --heat-${k}: ${val};`);
for (const [k, val] of Object.entries(t.spacing.tokens)) lines.push(`  --${k}: ${val};`);
for (const [k, val] of Object.entries(t.radius.tokens)) lines.push(`  --${k}: ${val};`);
for (const [k, val] of Object.entries(t.shadow.tokens)) lines.push(`  --${k}: ${val};`);
for (const [k, val] of Object.entries(t.motion.tokens)) lines.push(`  --${k}: ${val};`);
lines.push(`  --font-sans: ${t.type.families.sans.stack};`);
lines.push(`  --font-hebrew: ${t.type.families.hebrew.stack};`);
lines.push("  --radius: 0.625rem;");
for (const [k, val] of Object.entries(semantic("light"))) lines.push(`  --${k}: ${hsl(val)};`);
lines.push("}");
lines.push("");
lines.push(":root:root.dark,");
lines.push(".dark {");
for (const x of t.color.tokens) lines.push(`  --${x.name}: ${x.dark};`);
for (const [k, val] of Object.entries(semantic("dark"))) lines.push(`  --${k}: ${hsl(val)};`);
lines.push("}");
lines.push("");

// Dark-mode safety net for legacy markup that has no dark: variant.
// Text in a dark shade becomes the family's light step; light tinted grounds become the
// family's deepest step; white surfaces become the surface token. Specificity (0,2,0) beats a
// bare utility, and components' own dark: classes still win because Tailwind emits them later.
const families = {
  steel: ["steel", "blue", "indigo", "sky", "cyan", "violet", "purple", "fuchsia"],
  ember: ["ember", "orange", "primary"],
  moss: ["moss", "green", "emerald", "teal", "lime"],
  amber: ["amber", "yellow"],
  brick: ["brick", "red", "rose", "pink", "error"],
  ink: ["ink", "gray", "slate", "zinc", "neutral", "stone"],
};
const esc = (s) => s.replace(/\//g, "\\/");
lines.push("/* Dark-mode remap for legacy colour classes (generated). */");
for (const [scaleName, aliases] of Object.entries(families)) {
  const textSel = [], bgSel = [], borderSel = [];
  for (const a of aliases) {
    for (const step of ["500", "600", "700", "800", "900", "950"]) textSel.push(`.dark .text-${a}-${step}`);
    for (const step of ["50", "100", "200"]) {
      bgSel.push(`.dark .bg-${a}-${step}`);
      borderSel.push(`.dark .border-${a}-${step}`, `.dark .border-${a}-300`);
    }
  }
  const light = scaleName === "ink" ? S.ink["200"] : S[scaleName]["300"];
  lines.push(`${textSel.join(",\n")} {\n  color: ${light};\n}`);
  lines.push(`${bgSel.join(",\n")} {\n  background-color: ${scaleName === "ink" ? "#1E252D" : esc(S[scaleName]["950"])};\n}`);
  lines.push(`${[...new Set(borderSel)].join(",\n")} {\n  border-color: #3B4652;\n}`);
}
lines.push(`.dark .bg-white {\n  background-color: #171D24;\n}`);
lines.push(`.dark .text-black {\n  color: ${S.ink["100"]};\n}`);
lines.push("");

writeFileSync(join(root, "src/styles/tokens.css"), lines.join("\n"));
console.log("wrote src/styles/tokens.css");
